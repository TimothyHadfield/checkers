/* Make puzzles from engine self-play.
   node tools/make-puzzles.js [gamesPerVariant=10] [threads=4]
   A position becomes a puzzle when the side to move has one move (or a few equal ones) that is at least
   1.5 men better than every other move, that move leaves it at least 1 man ahead, and there are 2+ legal moves.
   The games are played by noisy mid-level players so that they contain mistakes worth punishing.
   Writes js/puzzles.js. */
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const path = require('path');
const fs = require('fs');
const R = require('../js/rules.js');
const E = require('../js/engine.js');

const DEPTH = 8;
function rng(seed) { let a = seed | 0; return () => { a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const boardStr = b => b.map(x => 'kmeMK'[x + 2]).join('');

// turn the engine's {from,to,caps} PV into full rules paths
function pvPaths(st, pv, max) {
  const out = [];
  let s = st;
  for (const p of pv.slice(0, max)) {
    if (s.result) break;
    const ms = R.legal(s).filter(m => m.path[0] === p.from && m.path[m.path.length - 1] === p.to);
    if (ms.length !== 1) break;
    out.push(ms[0].path);
    s = R.act(s, s.turn, { path: ms[0].path });
  }
  return out;
}

function gameFor(variant, seed) {
  const r = rng(seed);
  let st = R.newGame(variant);
  for (let i = 0; i < 4 && !st.result; i++) { const ms = R.legal(st); st = R.act(st, st.turn, { path: ms[Math.floor(r() * ms.length)].path }); }
  const found = [];
  E.clearTT();
  for (let ply = 0; ply < 160 && !st.result; ply++) {
    const legal = R.legal(st);
    if (legal.length >= 2 && ply >= 6) {
      const a = E.think(st, { depth: DEPTH, multi: true });
      const sorted = a.roots.slice().sort((x, y) => y.score - x.score);
      const best = sorted[0].score;
      const ok = sorted.filter(x => x.score >= best - 30);
      const rest = sorted.filter(x => x.score < best - 30);
      const second = rest.length ? rest[0].score : -E.MATE;
      const cap = s => Math.max(-2500, Math.min(2500, s));
      // a puzzle needs one clear answer, not just "take the piece that is hanging"
      const allCaps = legal.every(m => m.caps.length);
      if (best >= 100 && cap(best) - cap(second) >= 150 && ok.length <= 2 && !allCaps) {
        const line = pvPaths(st, a.pv, 7);
        if (line.length >= 3 && ok.some(x => R.samePath(x.move.path, line[0]))) {
          found.push({ v: variant, b: boardStr(st.board), t: st.turn, sol: ok.map(x => x.move.path), line, kind: E.isMate(best) ? 'win' : 'gain', gain: Math.round((cap(best) - cap(second)) / 10) / 10 });
        }
      }
    }
    // noisy mid-strength play so that mistakes happen
    const m = E.think(st, { depth: 4 + Math.floor(r() * 3), multi: true, noise: 70, seed: seed * 1000 + ply });
    st = R.act(st, st.turn, { path: m.move.path });
  }
  return found;
}

if (!isMainThread) {
  for (const j of workerData.jobs) parentPort.postMessage({ found: gameFor(j.variant, j.seed) });
  parentPort.postMessage({ done: true });
} else {
  const games = +process.argv[2] || 10;
  const threads = +process.argv[3] || 4;
  const jobs = [];
  for (const variant of R.VARIANT_IDS) for (let g = 0; g < (variant === 'american' ? games * 2 : games); g++) jobs.push({ variant, seed: 7000 + g * 31 + variant.length });
  const buckets = Array.from({ length: threads }, () => []);
  jobs.forEach((j, i) => buckets[i % threads].push(j));
  const all = [];
  let live = threads, n = 0;
  const t0 = Date.now();
  for (const b of buckets) {
    const w = new Worker(__filename, { workerData: { jobs: b } });
    w.on('message', m => {
      if (m.done) { if (--live === 0) finish(); return; }
      all.push(...m.found);
      console.error(++n + '/' + jobs.length + ' games, ' + all.length + ' candidates, ' + Math.round((Date.now() - t0) / 1000) + 's');
    });
    w.on('error', e => { console.error(e); process.exit(1); });
  }
  function finish() {
    const seen = new Set();
    const out = [];
    const per = {};
    // prefer the clearest puzzles; at most 40 per rule set; no repeated positions
    all.sort((a, b) => (b.kind === 'win') - (a.kind === 'win') || b.gain - a.gain);
    for (const p of all) {
      const k = p.v + p.b + p.t;
      if (seen.has(k) || (per[p.v] || 0) >= 40) continue;
      seen.add(k); per[p.v] = (per[p.v] || 0) + 1;
      out.push(p);
    }
    // easier ones first inside each rule set: shorter winning lines first
    out.sort((a, b) => a.v.localeCompare(b.v) || a.line.length - b.line.length);
    out.forEach((p, i) => { p.id = p.v.slice(0, 2) + (i + 1); });
    const body = '/* Puzzles: generated by tools/make-puzzles.js from engine self-play (' + new Date().toISOString().slice(0, 10) + ').\n   Each: v rules, b board (k/m = side 1 king/man, e empty, M/K = side 0), t side to move, sol accepted first moves, line the winning line. */\n' +
      "(function (root) { root.CkPuzzles = " + JSON.stringify(out) + "; })(typeof self !== 'undefined' ? self : this);\n";
    fs.writeFileSync(path.join(__dirname, '..', 'js', 'puzzles.js'), body);
    console.log(JSON.stringify(per), 'total', out.length, Math.round((Date.now() - t0) / 1000) + 's');
  }
}

/* Three-move openings for the "3-move ballot" option (American and Casual), as tournaments play it:
   the first three moves (Black, White, Black) are drawn at random, then the game goes on from there.
   The official lists are kept by the checkers federations; this one is our own: every legal 3-move start
   is searched by our engine and the ones it judges clearly lost for one side are left out.
     node tools/make-openings.js [nodes=1500000] [limit=55]   -> rewrites js/openings.js (~3 min)
   A start whose score is more than `limit` (centi-men, 100 = one man) from level is dropped. */
const fs = require('fs');
const path = require('path');
const R = require('../js/rules.js');
const E = require('../js/engine.js');

const NODES = +process.argv[2] || 1500000;
const LIMIT = +process.argv[3] || 55;
const all = [];
(function walk(st, line) {
  if (line.length === 3) { all.push({ st, line, text: line.text }); return; }
  for (const m of R.legal(st)) {
    const next = line.concat([m.path]);
    next.text = (line.text ? line.text + ' ' : '') + R.moveText('american', m.path, m.caps);
    walk(R.act(st, st.turn, { path: m.path }), next);
  }
})(R.newGame('american'), []);

const kept = [], dropped = [];
const t0 = Date.now();
for (const { st, line, text } of all) {
  E.clearTT();
  const r = E.think(st, { nodes: NODES });
  // score from Black's (side 0's) view
  const black = st.turn === 0 ? r.score : -r.score;
  (Math.abs(black) <= LIMIT && !E.isMate(r.score) ? kept : dropped).push({ line, black, text });
}
kept.sort((a, b) => a.text.localeCompare(b.text, 'en', { numeric: true }));
const out = '/* 3-move ballot openings, generated by tools/make-openings.js (' + new Date().toISOString().slice(0, 10) + '): ' +
  kept.length + ' of the ' + all.length + ' legal three-move starts\n' +
  '   (left out: ' + dropped.length + ' our engine scores more than ' + (LIMIT / 100) + ' of a man from level at ' + NODES + ' nodes).\n' +
  '   Each entry: the three move paths (square indices, American board). */\n' +
  '(function (root, factory) {\n  if (typeof module === \'object\' && module.exports) module.exports = factory();\n  else root.CkOpenings = factory();\n' +
  '})(typeof self !== \'undefined\' ? self : this, function () {\n  \'use strict\';\n  const BALLOT = ' + JSON.stringify(kept.map(k => k.line.slice())) + ';\n  return { BALLOT };\n});\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'openings.js'), out);
console.log(all.length + ' starts, kept ' + kept.length + ', dropped ' + dropped.length + ' in ' + Math.round((Date.now() - t0) / 1000) + 's');
for (const d of dropped) console.log('  dropped ' + d.text + '  (Black ' + (d.black > 0 ? '+' : '') + (d.black / 100).toFixed(2) + ')');
